void Display::begin()
{
    Wire.begin();
    Wire.setClock(400000);

    Wire.beginTransmission(OLED_I2C_ADDR);
    Wire.write(0x00); // control: command stream
    for (uint8_t i = 0; i < sizeof(kInit); ++i)
        Wire.write(pgm_read_byte(&kInit[i]));
    Wire.endTransmission();

    clear();
}

void Display::clear()
{
    memset(buf_, 0, sizeof(buf_));
    cursorCol_ = 0;
    cursorRow_ = 0;
    markDirty();
}

void Display::beginBatch()
{
    ++batchDepth_;
}

void Display::endBatch()
{
    if (batchDepth_ > 0 && --batchDepth_ == 0)
        flush();
}

void Display::setCursor(uint8_t col, uint8_t row)
{
    cursorCol_ = col;
    cursorRow_ = row;
}

void Display::setPixel(uint8_t lx, uint8_t ly, bool on)
{
    if (lx >= WIDTH || ly >= HEIGHT)
        return;
    // 90-degree rotation: landscape (lx,ly) -> native portrait (nx,ny).
    // If text comes out upside down, use nx = ly / ny = WIDTH-1-lx instead.
    uint8_t nx = (uint8_t)(HEIGHT - 1 - ly); // 0..63 -> SH1107 column
    uint8_t ny = lx;                         // 0..127 -> SH1107 row
    uint16_t idx = (uint16_t)nx + (uint16_t)(ny >> 3) * 64;
    uint8_t mask = (uint8_t)(1u << (ny & 7));
    if (on)
        buf_[idx] |= mask;
    else
        buf_[idx] = (uint8_t)(buf_[idx] & ~mask);
}

void Display::drawChar(uint8_t col, uint8_t row, char c)
{
    uint8_t lx0 = (uint8_t)(col * 6);
    uint8_t ly0 = (uint8_t)(row * 8);
    uint8_t glyph = ((uint8_t)c < 0x20 || (uint8_t)c > 0x7F) ? 0 : (uint8_t)(c - 0x20);
    const uint8_t* g = &kFont[(uint16_t)glyph * 5];
    for (uint8_t cx = 0; cx < 6; ++cx)
    {
        uint8_t bits = (cx < 5) ? pgm_read_byte(g + cx) : 0x00;
        for (uint8_t by = 0; by < 8; ++by)
        {
            bool on = (by < 7) && (bits & (1u << by));
            setPixel((uint8_t)(lx0 + cx), (uint8_t)(ly0 + by), on);
        }
    }
}

void Display::print(const char* s)
{
    while (*s)
    {
        drawChar(cursorCol_, cursorRow_, *s++);
        if (cursorCol_ < 0xFF)
            ++cursorCol_;
    }
    markDirty();
}

void Display::print(const __FlashStringHelper* s)
{
    const char* p = reinterpret_cast<const char*>(s);
    char c;
    while ((c = (char)pgm_read_byte(p++)) != '\0')
    {
        drawChar(cursorCol_, cursorRow_, c);
        if (cursorCol_ < 0xFF)
            ++cursorCol_;
    }
    markDirty();
}

void Display::print(int32_t n)
{
    char tmp[12];
    ltoa((long)n, tmp, 10);
    print(tmp);
}

void Display::flush()
{
    if (!dirty_)
        return;
    for (uint8_t page = 0; page < 16; ++page)
    {
        Wire.beginTransmission(OLED_I2C_ADDR);
        Wire.write(0x00);                   // command stream
        Wire.write((uint8_t)(0xB0 | page)); // set page address
        Wire.write(0x00);                   // column low nibble = 0
        Wire.write(0x10);                   // column high nibble = 0
        Wire.endTransmission();

        const uint8_t* pbuf = &buf_[(uint16_t)page * 64];
        uint8_t col = 0;
        while (col < 64)
        {
            Wire.beginTransmission(OLED_I2C_ADDR);
            Wire.write(0x40); // control: data stream
            uint8_t n = 0;
            while (col < 64 && n < 16)
            {
                Wire.write(pbuf[col]);
                ++col;
                ++n;
            }
            Wire.endTransmission();
        }
    }
    dirty_ = false;
}
